# 3. Bullet - elongated octahedron (a spiky capsule)
# ---------------------------------------------------------------------------
def gen_bullet():
    verts = []
    faces = []

    # Top and bottom tips
    verts.append((0, 0, 1.0))    # 0: top
    verts.append((0, 0, -1.0))   # 1: bottom

    # Middle ring (4 points)
    ring = [
        (0.15, 0, 0),
        (0, 0.15, 0),
        (-0.15, 0, 0),
        (0, -0.15, 0),
    ]
    verts.extend(ring)
    # 0=top, 1=bottom, 2..5=ring

    faces = [
        (0, 2, 3), (0, 3, 4), (0, 4, 5), (0, 5, 2),
        (1, 3, 2), (1, 4, 3), (1, 5, 4), (1, 2, 5),
    ]
    write_obj("bullet.obj", verts, faces)


