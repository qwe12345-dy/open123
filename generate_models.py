# 4. Star / Power-up - 3D extruded star
# ---------------------------------------------------------------------------
def gen_star():
    verts = []
    faces = []

    outer_r = 1.0
    inner_r = 0.45
    thickness = 0.25
    points = 5

    # Front face (z = +thickness/2)
    for i in range(points * 2):
        angle = math.pi / 2 + i * math.pi / points
        r = outer_r if i % 2 == 0 else inner_r
        x = r * math.cos(angle)
        y = r * math.sin(angle)
        verts.append((x, y, thickness / 2))

    # Back face (z = -thickness/2)
    for i in range(points * 2):
        angle = math.pi / 2 + i * math.pi / points
        r = outer_r if i % 2 == 0 else inner_r
        x = r * math.cos(angle)
        y = r * math.sin(angle)
        verts.append((x, y, -thickness / 2))

    n = points * 2  # 10 vertices per face

    # Front face (fan)
    for i in range(1, n - 1):
        faces.append((0, i, i + 1))
    # Back face (reversed winding)
    for i in range(1, n - 1):
        faces.append((n, n + i + 1, n + i))
    # Side walls
    for i in range(n):
        a = i
        b = (i + 1) % n
        faces.append((a, b, n + b))
        faces.append((a, n + b, n + a))

    write_obj("star.obj", verts, faces)


