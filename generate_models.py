#!/usr/bin/env python3
"""
Space Defender 3D - OBJ Model Generator
All models are hand-crafted as low-poly wireframe-style geometry.
Run: python3 generate_models.py
Outputs: models/*.obj
"""
import math
import os

MODELS_DIR = os.path.join(os.path.dirname(os.path.abspath(__file__)), "models")
os.makedirs(MODELS_DIR, exist_ok=True)


def write_obj(filename, vertices, faces):
    """Write a Wavefront OBJ file."""
    path = os.path.join(MODELS_DIR, filename)
    with open(path, "w") as f:
        f.write(f"# {filename} - generated by hand\n")
        f.write(f"# Vertices: {len(vertices)}, Faces: {len(faces)}\n")
        for v in vertices:
            f.write(f"v {v[0]:.4f} {v[1]:.4f} {v[2]:.4f}\n")
        for face in faces:
            # OBJ indices are 1-based
            idx = " ".join(str(i + 1) for i in face)
            f.write(f"f {idx}\n")
    print(f"  -> {path}  ({len(vertices)} verts, {len(faces)} faces)")


