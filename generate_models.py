# 5. Asteroid - rough icosahedron-ish rock
# ---------------------------------------------------------------------------
def gen_asteroid():
    verts = []
    faces = []

    # Icosahedron base
    t = (1.0 + math.sqrt(5.0)) / 2.0
    raw = [
        (-1, t, 0), (1, t, 0), (-1, -t, 0), (1, -t, 0),
        (0, -1, t), (0, 1, t), (0, -1, -t), (0, 1, -t),
        (t, 0, -1), (t, 0, 1), (-t, 0, -1), (-t, 0, 1),
    ]
    # Normalize and add slight random jitter for rocky look
    import random
    random.seed(42)
    for v in raw:
        length = math.sqrt(sum(c * c for c in v))
        scale = 0.6 / length * random.uniform(0.8, 1.2)
        verts.append((v[0] * scale, v[1] * scale, v[2] * scale))

    faces = [
        (0, 11, 5), (0, 5, 1), (0, 1, 7), (0, 7, 10), (0, 10, 11),
        (1, 5, 9), (5, 11, 4), (11, 10, 2), (10, 7, 6), (7, 1, 8),
        (3, 9, 4), (3, 4, 2), (3, 2, 6), (3, 6, 8), (3, 8, 9),
        (4, 9, 5), (2, 4, 11), (6, 2, 10), (8, 6, 7), (9, 8, 1),
    ]
    write_obj("asteroid.obj", verts, faces)


