# 2. Enemy Ship - flattened diamond / kite shape
# ---------------------------------------------------------------------------
def gen_enemy_ship():
    verts = []
    faces = []

    # Center top
    top = (0, 1.2, 0)
    verts.append(top)
    # Center bottom
    bottom = (0, -0.3, 0)
    verts.append(bottom)

    # Four corner points (flat diamond, pointing forward = +Z)
    corners = [
        (0, 0, 2.0),    # 2: front tip
        (1.5, 0, -0.8), # 3: right
        (0, 0, -1.5),   # 4: back
        (-1.5, 0, -0.8),# 5: left
    ]
    verts.extend(corners)

    # 0=top, 1=bottom, 2=front, 3=right, 4=back, 5=left
    faces = [
        # Top pyramid
        (0, 2, 3),
        (0, 3, 4),
        (0, 4, 5),
        (0, 5, 2),
        # Bottom pyramid
        (1, 3, 2),
        (1, 4, 3),
        (1, 5, 4),
        (1, 2, 5),
    ]
    write_obj("enemy_ship.obj", verts, faces)


